// Copies the side games' OFL fonts from @fontsource packages into assets/fonts and writes
// assets/fonts/neon-fonts.css, replacing the Google Fonts @imports (no third-party request,
// works offline / inside a Capacitor app). Same families and weights the pages asked Google for.
//
//   npm i --prefix <dir> @fontsource/orbitron @fontsource/rajdhani @fontsource/barlow @fontsource/barlow-condensed
//   node scripts/build_self_hosted_fonts.mjs <dir>/node_modules/@fontsource
import fs from 'node:fs';
import path from 'node:path';

const SRC = process.argv[2];
if (!SRC || !fs.existsSync(SRC)) { console.error('usage: node scripts/build_self_hosted_fonts.mjs <@fontsource dir>'); process.exit(1); }
const OUT = path.resolve('assets/fonts'), FILES = path.join(OUT, 'files');
const SUBSETS = new Set(['latin', 'latin-ext']);
const FACES = [
  ['orbitron', [600, 700, 800, 900], []],
  ['rajdhani', [500, 600, 700], []],
  ['barlow', [400, 500, 600, 700], []],
  ['barlow-condensed', [500, 600, 700, 800, 900], [700, 800, 900]],
];

fs.rmSync(FILES, { recursive: true, force: true });
fs.mkdirSync(FILES, { recursive: true });
const css = ['/* Self-hosted OFL-1.1 fonts (from @fontsource, see LICENSE-*.txt). Generated by scripts/build_self_hosted_fonts.mjs. */'];
const versions = [];
for (const [pkg, normal, italic] of FACES) {
  const dir = path.join(SRC, pkg), meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  versions.push(`${pkg}@${meta.version}`);
  fs.copyFileSync(path.join(dir, 'LICENSE'), path.join(OUT, `LICENSE-${pkg}.txt`));
  const sheets = [...normal.map(w => `${w}.css`), ...italic.map(w => `${w}-italic.css`)];
  for (const sheet of sheets) {
    const text = fs.readFileSync(path.join(dir, sheet), 'utf8');
    for (const block of text.split(/(?=\/\* )/)) {
      const name = block.match(/^\/\* (\S+) \*\//)?.[1];
      if (!name) continue;
      const subset = name.slice(pkg.length + 1).replace(/-\d+-(normal|italic)$/, '');
      if (!SUBSETS.has(subset)) continue;
      const file = `${name}.woff2`;
      fs.copyFileSync(path.join(dir, 'files', file), path.join(FILES, file));
      css.push(block.trim()
        .replace(/src: [^;]+;/, `src: url(./files/${file}) format('woff2');`));
    }
  }
}
css.splice(1, 0, `/* ${versions.join(', ')} */`);
fs.writeFileSync(path.join(OUT, 'neon-fonts.css'), css.join('\n') + '\n');
const total = fs.readdirSync(FILES).reduce((n, f) => n + fs.statSync(path.join(FILES, f)).size, 0);
console.log(`${fs.readdirSync(FILES).length} files, ${(total / 1024).toFixed(0)} KB → ${path.relative(process.cwd(), OUT)}`);
